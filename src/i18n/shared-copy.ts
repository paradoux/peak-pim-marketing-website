export function translateSharedCopy(locale: Locale, value: string) {
  return locale === "fr" ? frenchSharedCopy[value] ?? value : value;
}

export function localizeSharedMarkup(locale: Locale, html: string) {
  if (locale !== "fr") return html;

  return Object.entries(frenchSharedCopy)
    .sort(([left], [right]) => right.length - left.length)
    .reduce((localizedHtml, [source, translation]) => (
      localizedHtml
        .replaceAll(`>${source}<`, `>${translation}<`)
        .replaceAll(`aria-label="${source}"`, `aria-label="${translation}"`)
    ), html);
}
